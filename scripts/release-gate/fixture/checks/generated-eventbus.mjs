// Gate check — a GENERATED EventBus compiles against the packed packages.
//
// `connectum init --events <adapter>` writes an EventBus file, an event-handler
// service and the event protos that a consumer then compiles. Their text is
// produced by the CLI from templates, so a rename or a narrowed option type in
// @connectum/events or one of the adapter packages breaks the generated project
// while every hand-written fixture here still compiles. This check runs the
// PACKED CLI (`executeInit`, the code behind `connectum init`) once per adapter
// package, generates the protos with the consumer's own buf, and type-checks the
// whole generated project (`tsc --noEmit`, the generated tsconfig) with the
// packed @connectum/* packages resolved from this consumer's node_modules.
//
// The CLI fetches its base project (a pinned examples tag) over the network, as
// `connectum init` always does; a network failure fails the check, with the
// CLI's own message.
import { spawnSync } from "node:child_process";
import { existsSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(".");
const GENERATED = join(ROOT, "generated");
const TSC = join(ROOT, "node_modules", "typescript", "bin", "tsc");
// One generated project per adapter package: redpanda reuses the Kafka adapter.
const ADAPTERS = ["nats", "kafka", "redis", "amqp"];

const { executeInit } = await import("@connectum/cli/commands/init");

rmSync(GENERATED, { recursive: true, force: true });
const failures = [];

function run(label, cmd, args, cwd) {
    // buf runs protoc-gen-es from PATH; the consumer's own node_modules provide it.
    const env = { ...process.env, PATH: `${join(ROOT, "node_modules", ".bin")}:${process.env.PATH}` };
    const r = spawnSync(cmd, args, { cwd, env, encoding: "utf8" });
    if (r.status !== 0) {
        failures.push(`${label}: ${cmd} ${args.join(" ")} exited ${r.status}\n${(r.stdout ?? "") + (r.stderr ?? "")}`.trimEnd());
        return false;
    }
    return true;
}

for (const adapter of ADAPTERS) {
    const dir = join(GENERATED, `eventbus-${adapter}`);
    const label = `generated EventBus (${adapter})`;
    try {
        await executeInit({ name: dir, events: adapter, yes: true });
    } catch (error) {
        failures.push(`${label}: connectum init failed: ${error instanceof Error ? error.message : String(error)}`);
        continue;
    }
    if (!existsSync(join(dir, "src", "greeterEventBus.ts"))) {
        failures.push(`${label}: init did not write src/greeterEventBus.ts`);
        continue;
    }
    if (!run(label, join(ROOT, "node_modules", ".bin", "buf"), ["generate"], dir)) continue;
    if (run(label, process.execPath, [TSC, "--noEmit", "-p", join(dir, "tsconfig.json")], dir)) {
        console.log(`  ${label}: init + buf generate + tsc --noEmit OK`);
    }
}

if (failures.length === 0) {
    console.log(`generated-eventbus: OK — ${ADAPTERS.join(", ")} projects generated by the packed CLI type-check against the packed packages`);
    process.exit(0);
}
console.log(`generated-eventbus: FAIL — ${failures.length} problem(s):`);
for (const f of failures) console.log(`  ${f.replaceAll("\n", "\n    ")}`);
process.exit(1);
